const DICTS: Record<Locale, Dict> = { 'zh-CN': zh, en };

const STORAGE_KEY = 'jsona.locale';

export function getStoredLocale(): Locale {
  if (typeof localStorage === 'undefined') return 'zh-CN';
  const v = localStorage.getItem(STORAGE_KEY);
  return v === 'en' ? 'en' : 'zh-CN';
}

export function setStoredLocale(loc: Locale) {
  if (typeof localStorage === 'undefined') return;
  localStorage.setItem(STORAGE_KEY, loc);
}

export function translate(loc: Locale, key: string): string {
  return DICTS[loc][key] ?? DICTS['zh-CN'][key] ?? key;
}

// ---------------------------------------------------------------------------
// React context: lets any component read the active translation function via
// useT() instead of receiving `t` as a prop. App remains the single source of
// truth for the locale state.
// ---------------------------------------------------------------------------

interface I18nContextValue {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({
  locale,
  setLocale,
  children,
}: {
  locale: Locale;
  setLocale: (l: Locale) => void;
  children: ReactNode;
}) {
  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale,
      t: (key: string) => translate(locale, key),
    }),
    [locale, setLocale],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

/** Returns the translation function bound to the current locale. */
export function useT(): (key: string) => string {
  const ctx = useContext(I18nContext);
  if (!ctx) return (key: string) => translate('zh-CN', key);
  return ctx.t;
}

/** Returns the raw locale + setter for components that need to switch language. */
export function useI18nState() {
  const ctx = useContext(I18nContext);
  if (!ctx) return { locale: 'zh-CN' as Locale, setLocale: () => {} };
  return { locale: ctx.locale, setLocale: ctx.setLocale };
}
